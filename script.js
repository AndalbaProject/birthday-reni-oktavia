const candleHint = $("candleHint");
const flames = () => [...candleSec.querySelectorAll(".candle .flame:not(.out)")];

function showCandles() {
  candleSec.classList.remove("hidden");
  window.scrollTo(0, 0);
}

let blowing = null;
function extinguishOne() {
  const left = flames();
  if (!left.length) return;
  left[(Math.random() * left.length) | 0].classList.add("out");
  if (!flames().length) allOut();
}
function allOut() {
  stopBlowing();
  blowBtn.disabled = true;
  blowBtn.textContent = "✨ Permintaan terkirim! ✨";
  candleHint.textContent = "yeayyy semua api padam, semoga wish-mu terkabul ya, Reni! 🩷";
  burstPetals(50);
  goldConfetti(80);
  setTimeout(() => {
    candleSec.classList.add("fade-out");
    setTimeout(() => {
      candleSec.classList.add("hidden");
      main.classList.remove("hidden");
      initReveal();
      window.scrollTo(0, 0);
    }, 700);
  }, 1600);
}
function startBlowing() {
  if (blowing || !flames().length) return;
  extinguishOne();
  blowing = setInterval(extinguishOne, 450);
  blowBtn.classList.add("pressing");
}
function stopBlowing() {
  if (blowing) { clearInterval(blowing); blowing = null; }
  blowBtn.classList.remove("pressing");
}
blowBtn.addEventListener("pointerdown", startBlowing);
blowBtn.addEventListener("pointerup", stopBlowing);
blowBtn.addEventListener("pointerleave", stopBlowing);
blowBtn.addEventListener("pointercancel", stopBlowing);
blowBtn.addEventListener("contextmenu", (e) => e.preventDefault());

/* ============================================================
   REVEAL ON SCROLL
   ============================================================ */
function initReveal() {
  const obs = new IntersectionObserver(
    (entries) => entries.forEach((e) => { if (e.isIntersecting) e.target.classList.add("in"); }),
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  document.querySelectorAll(".reveal").forEach((el) => obs.observe(el));
}

