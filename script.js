/* ---------- digital rain (blue & burgundy matrix) ---------- */
function startDigitalRain() {
  const canvas = $("rainCanvas");
  if (!canvas) return () => { };
  const ctx = canvas.getContext("2d");
  let w, h, cols, drops, raf;
  const glyphs = "01アイウエオカキ❤♡01ABCDEF<>*+".split("");
  const FS = 16;
  function resize() {
    w = canvas.width = innerWidth;
    h = canvas.height = innerHeight;
    cols = Math.floor(w / FS);
    drops = Array(cols).fill(0).map(() => Math.random() * -50);
  }
  resize();
  window.addEventListener("resize", resize);
  function draw() {
    ctx.fillStyle = "rgba(255, 245, 249, 0.22)";
    ctx.fillRect(0, 0, w, h);
    ctx.font = FS + "px monospace";
    for (let i = 0; i < cols; i++) {
      const ch = glyphs[(Math.random() * glyphs.length) | 0];
      const x = i * FS, y = drops[i] * FS;
      ctx.fillStyle = Math.random() > 0.5
        ? (Math.random() > 0.85 ? "#f3a9cf" : "#d9649f")
        : (Math.random() > 0.85 ? "#b04a80" : "#e58ab8");
      ctx.fillText(ch, x, y);
      if (y > h && Math.random() > 0.975) drops[i] = 0;
      drops[i] += 0.6 + Math.random() * 0.5;
    }
    raf = requestAnimationFrame(draw);
  }
  if (!reduceMotion) draw();
  return () => { cancelAnimationFrame(raf); window.removeEventListener("resize", resize); };
}
