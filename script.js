/* ---------- gold & sapphire confetti burst (canvas) ---------- */
function goldConfetti(count) {
  if (reduceMotion) return;
  const c = document.createElement("canvas");
  c.style.cssText = "position:fixed;inset:0;z-index:185;pointer-events:none";
  c.width = innerWidth; c.height = innerHeight;
  document.body.appendChild(c);
  const ctx = c.getContext("2d");
  const colors = ["#d9a93f", "#fff6dd", "#f3a9cf", "#d9649f", "#e58ab8", "#b04a80", "#ffffff"];
  const parts = Array.from({ length: count }, () => ({
    x: innerWidth / 2, y: innerHeight / 2,
    vx: (Math.random() - 0.5) * 14,
    vy: Math.random() * -15 - 4,
    g: 0.32 + Math.random() * 0.12,
    s: 5 + Math.random() * 7,
    rot: Math.random() * 6.28,
    vr: (Math.random() - 0.5) * 0.4,
    col: colors[(Math.random() * colors.length) | 0],
    life: 0,
  }));
  let frame = 0;
  (function tick() {
    ctx.clearRect(0, 0, c.width, c.height);
    frame++;
    parts.forEach((p) => {
      p.vy += p.g; p.x += p.vx; p.y += p.vy; p.vx *= 0.99; p.rot += p.vr; p.life++;
      ctx.save();
      ctx.translate(p.x, p.y); ctx.rotate(p.rot);
      ctx.globalAlpha = Math.max(0, 1 - frame / 130);
      ctx.fillStyle = p.col;
      ctx.fillRect(-p.s / 2, -p.s / 2, p.s, p.s * 0.6);
      ctx.restore();
    });
    if (frame < 130) requestAnimationFrame(tick);
    else c.remove();
  })();
}

